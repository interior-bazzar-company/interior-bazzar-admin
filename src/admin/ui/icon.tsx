/* =============================================================================
   ui/icon — ONE icon language: @untitledui/icons.
   -----------------------------------------------------------------------------
   The panel used to draw ninety paths of its own. It draws none now: every
   glyph is Untitled UI's, on one 24-grid at one stroke weight, so an icon in
   the nav, an icon in a button and an icon in a table cell are optically one
   set.

   `Icon name="…"` stays as the panel's own vocabulary — `deal`, `quote`,
   `cash`, `chevr` — because a hundred and fifty files already say those
   words, and a name that means "the deal icon" is more useful to a screen
   than the library's `Briefcase01`. The map below is the whole translation.
   A view may also import a glyph straight from `@untitledui/icons` and hand
   it to a component that takes `icon={…}` — both routes reach the same set.

   An unknown name renders the document glyph rather than nothing: a missing
   icon should be a wrong drawing somebody notices, never an invisible gap in
   a toolbar that silently changes the spacing of everything beside it.

   SIZES. xs 12 · sm 16 · (md) 20 · lg 24 · xl 32. Stroke follows Untitled
   UI's convention: 2px at 20, tightened to 2.25 at 16 and below so a small
   glyph does not go thin.
   ========================================================================== */
