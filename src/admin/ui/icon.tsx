export type IconName = keyof typeof ICONS;

const SIZES = {
    xs: "size-3 stroke-[2.5px]",
    sm: "size-4 stroke-[2.25px]",
    md: "size-5",
    lg: "size-6",
    xl: "size-8 stroke-[1.75px]",
} as const;

export function Icon({
    name,
    size = "md",
    className,
    ...rest
}: {
    name: string;
    size?: keyof typeof SIZES;
    className?: string;
} & Omit<SVGProps<SVGSVGElement>, "name" | "className">) {
    const Glyph = ICONS[name] || ICONS.doc;
    return <Glyph aria-hidden="true" data-icon className={cx("shrink-0", SIZES[size], className)} {...rest} />;
}

/** The glyph itself, for components that take `icon={Component}`. */
export const iconOf = (name: string): IconComponent => ICONS[name] || ICONS.doc;
